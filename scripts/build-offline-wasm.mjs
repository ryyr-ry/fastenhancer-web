// Build additional offline assets only. Existing real-time binaries are untouched.
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const output = join(root, 'dist/wasm/offline');
const compiler = process.env.EMCC || 'emcc';
const version = spawnSync(compiler, ['--version'], { encoding: 'utf8' });
if (version.error) throw version.error;
if (version.status !== 0 || !/\b3\.1\.69\b/.test(version.stdout)) throw new Error('Offline assets require Emscripten 3.1.69; changing compiler versions requires numerical compatibility validation.');
mkdirSync(output, { recursive: true });
const common = readdirSync(join(root, 'src/engine/common')).filter(f => f.endsWith('.c')).sort().map(f => join(root, 'src/engine/common', f));
const selected = process.argv.slice(2);
const models = selected.length ? selected : ['tiny', 'base', 'small'];
const exports = ['malloc', 'free', 'fe_init', 'fe_destroy', 'fe_process', 'fe_process_inplace', 'fe_get_input_ptr', 'fe_get_output_ptr', 'fe_get_hop_size', 'fe_get_n_fft', 'fe_set_agc', 'fe_set_hpf', 'fe_reset', 'fe_offline_info', 'fe_offline_encode', 'fe_offline_gru', 'fe_offline_attention', 'fe_offline_decode'];
for (const model of models) {
  if (!['tiny', 'base', 'small'].includes(model)) throw new Error(`Unknown model: ${model}`);
  // Scalar calls retain the published engine to preserve its rounding.
  for (const variant of ['simd']) {
    const path = join(output, `fastenhancer-${model}-${variant}-offline.wasm`);
    const args = ['--no-entry', '-std=c11', '-O3', '-flto', '-sSTANDALONE_WASM=1', '-sALLOW_MEMORY_GROWTH=0', '-sINITIAL_MEMORY=16777216', '-sSTACK_SIZE=65536', '-sFILESYSTEM=0', '-sABORTING_MALLOC=0',
      `-sEXPORTED_FUNCTIONS=${JSON.stringify(exports.map(x => `_${x}`))}`,
      '-I', join(root, 'src/engine'), '-I', join(root, 'src/engine/common'), '-I', join(root, 'src/engine/configs'),
      `-DFE_USE_${model.toUpperCase()}_48K`, join(root, 'src/engine/offline.c'), join(root, 'src/engine/exports.c'), join(root, 'src/engine/pipeline.c'), ...common, '-o', path];
    if (variant === 'simd') args.push('-msimd128');
    const result = spawnSync(compiler, args, { stdio: 'inherit' });
    if (result.error) throw result.error;
    if (result.status !== 0) process.exit(result.status || 1);
    const bytes = readFileSync(path), module = new WebAssembly.Module(bytes), map = {};
    for (const item of WebAssembly.Module.exports(module)) if (item.kind === 'function') {
      if (exports.includes(item.name)) map[`_${item.name}`] = item.name;
      else if (item.name === '_initialize') map._initialize = item.name;
    }
    for (const name of exports) if (!map[`_${name}`]) throw new Error(`Missing offline export: ${name}`);
    const source = `// Generated by scripts/build-offline-wasm.mjs; offline-only binary.\nconst base64 = ${JSON.stringify(bytes.toString('base64'))};\nlet cached: ArrayBuffer | undefined;\nexport function getWasmBytes(): ArrayBuffer {\n  if (!cached) { const binary = atob(base64); const bytes = new Uint8Array(binary.length); for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i); cached = bytes.buffer; }\n  return cached;\n}\nexport const exportMap: Record<string, string> = ${JSON.stringify(map, null, 2)};\n`;
    writeFileSync(join(root, `src/embedded/offline-${model}-${variant}.ts`), source);
    console.log(`Built ${model}/${variant} offline engine (${bytes.byteLength} bytes)`);
  }
}
